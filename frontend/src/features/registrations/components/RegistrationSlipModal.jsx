import React from 'react';
import {
  Dialog,
  DialogTitle,
  DialogContent,
  DialogActions,
  Button,
  Box,
  Typography,
  Grid,
  Chip,
} from '@mui/material';
import {
  Print as PrintIcon,
  WhatsApp as WhatsAppIcon,
  HowToReg as ConvertIcon,
  QrCode2 as QrCodeIcon,
} from '@mui/icons-material';
import { useQuery } from '@tanstack/react-query';
import { dynamicRegistrationApi } from '../api/dynamicRegistrationApi';
import { printElement } from '../../../utils/printUtils';

const DEFAULT_CONFIG = {
  primaryColor: '#0284c7',
  secondaryColor: '#f0f9ff',
  accentColor: '#0369a1',
  borderColor: '#0284c7',
  fontFamily: 'Inter, sans-serif',
  fontScalePercent: 100,
  headerLayout: 'Classic',
  borderStyle: 'Solid',
  logoSize: 52,
  photoWidth: 76,
  photoHeight: 92,
  pageSize: 'A4',
  pageOrientation: 'portrait',
  pageMargin: '6mm',
  pagePadding: 16,
  pageMaxWidth: 780,

  slipTitle: 'OFFICIAL STUDENT REGISTRATION SLIP',
  slipTitleBgColor: '#0284c7',
  slipTitleTextColor: '#ffffff',

  showSchoolLogo: true,
  showAffiliationNo: true,
  showStudentPhotoBox: true,
  showQrCode: true,
  showPreviousSchool: true,
  showFeeBreakdown: true,
  showPaymentMode: true,
  showSchoolSealBox: true,
  showDeclaration: true,
  showSignatures: true,

  signature1: 'Candidate / Parent Signature',
  signature2: 'Verification Officer',
  signature3: 'Authorized Seal & Signature',

  declarationTitle: 'DECLARATION / UNDERTAKING:',
  declarationText:
    'I hereby certify that all information submitted during registration is genuine and accurate. I understand that registration does not guarantee admission until all eligibility conditions and fee payments are satisfied.',

  footerText: 'Official Student Registration Slip • System Generated by School ERP',

  sections: [
    { key: 'header', title: 'School Header & Affiliation', visible: true, order: 1 },
    { key: 'meta_bar', title: 'Registration Reference & Status Bar', visible: true, order: 2 },
    { key: 'student_info', title: 'Student Information & Seeking Class', visible: true, order: 3 },
    { key: 'parents_info', title: 'Parent & Contact Details', visible: true, order: 4 },
    { key: 'fee_summary', title: 'Registration Fee & Payment Ledger', visible: true, order: 5 },
    { key: 'address_school', title: 'Residential Address & Previous School', visible: true, order: 6 },
    { key: 'declaration', title: 'Declaration & Undertaking', visible: true, order: 7 },
    { key: 'signatures', title: 'Signatures & School Seal', visible: true, order: 8 },
    { key: 'footer', title: 'Footer System Note', visible: true, order: 9 },
  ],
};

export const RegistrationSlipModal = ({ open, onClose, slip, branchInfo = {}, onAdmit }) => {
  if (!slip) return null;

  // Fetch Dynamic Registration Slip Layout & Styling configured in Super Admin
  const { data: configRes } = useQuery({
    queryKey: ['registration-slip-config'],
    queryFn: () => dynamicRegistrationApi.getRegistrationSlipConfig(),
    staleTime: 60000,
  });

  const cfg = {
    ...DEFAULT_CONFIG,
    ...(configRes?.data?.data || {}),
  };

  const schoolName = cfg.headerSchoolNameCustom?.trim() || branchInfo.schoolName || 'DELHI PUBLIC SCHOOL';
  const branchName = branchInfo.branchName || 'Main Campus';
  const schoolPhone = branchInfo.phone || '+91 9873993957';
  const schoolSubtitle = cfg.headerSubtitleCustom?.trim() || `Branch: ${branchName} • Ph: ${schoolPhone} • CBSE Affiliation No: 2026/0912`;
  const schoolAddress = cfg.headerAddressCustom?.trim() || branchInfo.address || 'Knowledge Park, Educational Zone, Greater Noida, UP - 201306';
  const logoUrl = '/dvslogo1.jpeg';
  const fontMultiplier = (cfg.fontScalePercent || 100) / 100;

  const handlePrint = () => {
    printElement('printable-registration-slip', {
      title: `Registration_Slip_${slip.slipNumber}_${slip.studentName}`,
      pageSize: cfg.pageSize || 'A4',
      orientation: cfg.pageOrientation || 'portrait',
      margin: cfg.pageMargin || '6mm',
    });
  };

  const handleShareWhatsApp = () => {
    const rawNumber = slip.contactNumber ? String(slip.contactNumber).replace(/\D/g, '') : '';
    const phone = rawNumber.length === 10 ? `91${rawNumber}` : rawNumber;
    const msg = `*STUDENT REGISTRATION SLIP - ${schoolName}*\n\nDear Parent/Student,\nRegistration has been successfully recorded!\n\n*Slip No:* ${slip.slipNumber}\n*Student Name:* ${slip.studentName}\n*Class:* ${slip.className}\n*Registration Fee:* Rs. ${slip.feeAmount}\n*Paid Amount:* Rs. ${slip.paidAmount}\n*Balance Due:* Rs. ${slip.balanceAmount}\n*Payment Status:* ${slip.paymentStatus}\n\nThank you for choosing ${schoolName}!`;
    const url = `https://api.whatsapp.com/send?phone=${phone}&text=${encodeURIComponent(msg)}`;
    window.open(url, '_blank');
  };

  const sortedSections = [...(cfg.sections || DEFAULT_CONFIG.sections)].sort((a, b) => a.order - b.order);

  // Render individual sections dynamically based on designer configuration
  const renderSection = (key) => {
    switch (key) {
      case 'header':
        return (
          <Box key="header" sx={{ borderBottom: `2px solid ${cfg.borderColor}`, pb: 1, mb: 1.2 }}>
            <Grid container alignItems="center" spacing={1.5}>
              {cfg.showSchoolLogo && (
                <Grid item xs={2} sx={{ textAlign: 'center' }}>
                  <img
                    src={logoUrl}
                    alt="School Logo"
                    style={{
                      width: cfg.logoSize || 52,
                      height: cfg.logoSize || 52,
                      objectFit: 'contain',
                      borderRadius: 6,
                      border: '1px solid #e2e8f0',
                      padding: 2,
                    }}
                    onError={(e) => {
                      e.target.style.display = 'none';
                    }}
                  />
                </Grid>
              )}
              <Grid item xs={cfg.showSchoolLogo ? (cfg.showStudentPhotoBox ? 7.5 : 10) : (cfg.showStudentPhotoBox ? 9.5 : 12)}>
                <Typography
                  variant="subtitle1"
                  sx={{
                    color: cfg.headerSchoolNameColor || cfg.primaryColor,
                    fontWeight: cfg.headerSchoolNameFontWeight || '900',
                    textTransform: cfg.headerSchoolNameTransform || 'uppercase',
                    fontSize: `${1.1 * fontMultiplier}rem`,
                    lineHeight: 1.15,
                  }}
                >
                  {schoolName}
                </Typography>
                <Typography variant="caption" sx={{ color: cfg.primaryColor, fontWeight: 700, display: 'block', fontSize: `${0.72 * fontMultiplier}rem` }}>
                  {schoolSubtitle}
                </Typography>
                <Typography variant="caption" sx={{ color: '#64748b', display: 'block', fontSize: `${0.68 * fontMultiplier}rem`, lineHeight: 1.1 }}>
                  {schoolAddress}
                </Typography>
              </Grid>

              {cfg.showStudentPhotoBox && (
                <Grid item xs={2.5} sx={{ textAlign: 'right' }}>
                  <Box
                    sx={{
                      width: cfg.photoWidth || 76,
                      height: cfg.photoHeight || 92,
                      border: `1.5px dashed ${cfg.borderColor}`,
                      borderRadius: 1,
                      bgcolor: cfg.secondaryColor,
                      display: 'flex',
                      flexDirection: 'column',
                      alignItems: 'center',
                      justifyContent: 'center',
                      ml: 'auto',
                      p: 0.5,
                    }}
                  >
                    <Typography variant="caption" sx={{ fontSize: '0.6rem', color: '#64748b', textAlign: 'center', fontWeight: 700 }}>
                      AFFIX PHOTO
                    </Typography>
                  </Box>
                </Grid>
              )}
            </Grid>
          </Box>
        );

      case 'meta_bar':
        return (
          <Box key="meta_bar" sx={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', mb: 1.2, px: 0.5 }}>
            <Box sx={{ bgcolor: cfg.slipTitleBgColor || cfg.primaryColor, color: cfg.slipTitleTextColor || '#ffffff', px: 1.2, py: 0.3, borderRadius: 1 }}>
              <Typography variant="caption" fontWeight={900} sx={{ letterSpacing: 0.5, fontSize: `${0.7 * fontMultiplier}rem`, textTransform: 'uppercase' }}>
                {cfg.slipTitle || 'REGISTRATION SLIP'}
              </Typography>
            </Box>
            <Typography variant="caption" fontWeight={800} sx={{ color: '#0f172a', fontSize: `${0.78 * fontMultiplier}rem` }}>
              Slip No: <span style={{ color: cfg.primaryColor, fontFamily: 'monospace' }}>{slip.slipNumber}</span>
            </Typography>
            <Typography variant="caption" sx={{ color: '#64748b', fontSize: `${0.72 * fontMultiplier}rem` }}>
              Session: <strong>{slip.academicYearName || '2026-2027'}</strong> &bull; Date: <strong>{new Date(slip.createdOn || Date.now()).toLocaleDateString()}</strong>
            </Typography>
          </Box>
        );

      case 'student_info':
        return (
          <Box key="student_info" sx={{ bgcolor: cfg.secondaryColor, p: 1.2, borderRadius: 1.2, border: '1px solid #e2e8f0', mb: 1.2 }}>
            <Grid container spacing={1}>
              <Grid item xs={4}>
                <Typography variant="caption" sx={{ color: '#64748b', fontSize: '0.68rem', display: 'block' }}>Student Name</Typography>
                <Typography variant="body2" fontWeight={800} sx={{ fontSize: `${0.84 * fontMultiplier}rem` }}>{slip.studentName}</Typography>
              </Grid>
              <Grid item xs={4}>
                <Typography variant="caption" sx={{ color: '#64748b', fontSize: '0.68rem', display: 'block' }}>Seeking Class</Typography>
                <Typography variant="body2" fontWeight={800} sx={{ fontSize: `${0.84 * fontMultiplier}rem` }}>{slip.className}</Typography>
              </Grid>
              <Grid item xs={4}>
                <Typography variant="caption" sx={{ color: '#64748b', fontSize: '0.68rem', display: 'block' }}>Mobile Number</Typography>
                <Typography variant="body2" fontWeight={800} sx={{ fontSize: `${0.84 * fontMultiplier}rem` }}>{slip.contactNumber}</Typography>
              </Grid>
              <Grid item xs={4}>
                <Typography variant="caption" sx={{ color: '#64748b', fontSize: '0.68rem', display: 'block' }}>Father's Name</Typography>
                <Typography variant="body2" fontWeight={600} sx={{ fontSize: `${0.82 * fontMultiplier}rem` }}>{slip.fatherName || 'N/A'}</Typography>
              </Grid>
              <Grid item xs={4}>
                <Typography variant="caption" sx={{ color: '#64748b', fontSize: '0.68rem', display: 'block' }}>Mother's Name</Typography>
                <Typography variant="body2" fontWeight={600} sx={{ fontSize: `${0.82 * fontMultiplier}rem` }}>{slip.motherName || 'N/A'}</Typography>
              </Grid>
              <Grid item xs={4}>
                <Typography variant="caption" sx={{ color: '#64748b', fontSize: '0.68rem', display: 'block' }}>Gender / DOB</Typography>
                <Typography variant="body2" fontWeight={600} sx={{ fontSize: `${0.82 * fontMultiplier}rem` }}>
                  {slip.gender || 'N/A'} {slip.dob ? `(${new Date(slip.dob).toLocaleDateString()})` : ''}
                </Typography>
              </Grid>
            </Grid>
          </Box>
        );

      case 'parents_info':
        return null; // Merged with student_info for compact 1/3 A4 layout

      case 'address_school':
        if (!slip.address && !slip.previousSchool) return null;
        return (
          <Box key="address_school" sx={{ px: 1, py: 0.6, bgcolor: '#f8fafc', borderRadius: 1, border: '1px solid #e2e8f0', mb: 1.2 }}>
            <Grid container spacing={1}>
              {slip.address && (
                <Grid item xs={slip.previousSchool ? 7 : 12}>
                  <Typography variant="caption" sx={{ color: '#64748b', fontSize: '0.65rem', display: 'block' }}>Address</Typography>
                  <Typography variant="caption" fontWeight={600} sx={{ color: '#1e293b', fontSize: `${0.75 * fontMultiplier}rem` }}>
                    {slip.address} {slip.city ? `, ${slip.city}` : ''} {slip.state ? `(${slip.state})` : ''}
                  </Typography>
                </Grid>
              )}
              {slip.previousSchool && (
                <Grid item xs={slip.address ? 5 : 12}>
                  <Typography variant="caption" sx={{ color: '#64748b', fontSize: '0.65rem', display: 'block' }}>Previous School</Typography>
                  <Typography variant="caption" fontWeight={600} sx={{ color: '#1e293b', fontSize: `${0.75 * fontMultiplier}rem` }}>
                    {slip.previousSchool}
                  </Typography>
                </Grid>
              )}
            </Grid>
          </Box>
        );

      case 'fee_summary':
        if (!cfg.showFeeBreakdown) return null;
        return (
          <Grid key="fee_summary" container spacing={1} sx={{ mb: 1.2 }}>
            <Grid item xs={4}>
              <Box sx={{ p: 0.8, bgcolor: '#f0f9ff', borderRadius: 1, border: '1px solid #bae6fd', textAlign: 'center' }}>
                <Typography variant="caption" sx={{ color: '#0369a1', fontWeight: 800, fontSize: '0.65rem' }}>Registration Fee</Typography>
                <Typography variant="subtitle2" fontWeight={900} sx={{ color: '#0c4a6e', fontSize: '0.92rem' }}>₹{slip.feeAmount}</Typography>
              </Box>
            </Grid>
            <Grid item xs={4}>
              <Box sx={{ p: 0.8, bgcolor: '#f0fdf4', borderRadius: 1, border: '1px solid #bbf7d0', textAlign: 'center' }}>
                <Typography variant="caption" sx={{ color: '#15803d', fontWeight: 800, fontSize: '0.65rem' }}>Paid Amount</Typography>
                <Typography variant="subtitle2" fontWeight={900} sx={{ color: '#14532d', fontSize: '0.92rem' }}>₹{slip.paidAmount}</Typography>
              </Box>
            </Grid>
            <Grid item xs={4}>
              <Box sx={{ p: 0.8, bgcolor: '#fef2f2', borderRadius: 1, border: '1px solid #fecaca', textAlign: 'center' }}>
                <Typography variant="caption" sx={{ color: '#b91c1c', fontWeight: 800, fontSize: '0.65rem' }}>Balance Due</Typography>
                <Typography variant="subtitle2" fontWeight={900} sx={{ color: '#991b1b', fontSize: '0.92rem' }}>₹{slip.balanceAmount}</Typography>
              </Box>
            </Grid>
          </Grid>
        );

      case 'declaration':
        if (!cfg.showDeclaration) return null;
        return (
          <Box key="declaration" sx={{ bgcolor: '#fafafa', p: 0.8, borderRadius: 1, border: '1px solid #e5e7eb', mb: 1.2 }}>
            <Typography variant="caption" fontWeight={800} sx={{ color: cfg.primaryColor, fontSize: '0.65rem', display: 'block' }}>
              {cfg.declarationTitle}
            </Typography>
            <Typography variant="caption" sx={{ color: '#4b5563', fontSize: '0.62rem', lineHeight: 1.15, display: 'block' }}>
              {cfg.declarationText}
            </Typography>
          </Box>
        );

      case 'signatures':
        if (!cfg.showSignatures) return null;
        return (
          <Box key="signatures" sx={{ pt: 1, borderTop: '1px dashed #cbd5e1', display: 'flex', justifyContent: 'space-between', alignItems: 'flex-end' }}>
            <Box sx={{ textAlign: 'center', minWidth: 120 }}>
              <Box sx={{ borderBottom: '1px solid #0f172a', height: 18, mb: 0.3 }} />
              <Typography variant="caption" fontWeight={700} sx={{ fontSize: '0.65rem', color: '#475569' }}>
                {cfg.signature1}
              </Typography>
            </Box>

            {cfg.showQrCode && (
              <Box sx={{ textAlign: 'center' }}>
                <QrCodeIcon sx={{ fontSize: 30, color: cfg.primaryColor }} />
                <Typography variant="caption" sx={{ display: 'block', fontSize: '0.58rem', color: '#94a3b8' }}>
                  VERIFIED
                </Typography>
              </Box>
            )}

            {cfg.showSchoolSealBox && (
              <Box sx={{ textAlign: 'center', minWidth: 140 }}>
                <Box sx={{ borderBottom: '1px solid #0f172a', height: 18, mb: 0.3 }} />
                <Typography variant="caption" fontWeight={800} sx={{ fontSize: '0.68rem', color: '#0f172a' }}>
                  {cfg.signature3}
                </Typography>
              </Box>
            )}
          </Box>
        );

      case 'footer':
        return (
          <Box key="footer" sx={{ mt: 1, textAlign: 'center' }}>
            <Typography variant="caption" sx={{ color: '#94a3b8', fontSize: '0.6rem' }}>
              {cfg.footerText}
            </Typography>
          </Box>
        );

      default:
        return null;
    }
  };

  return (
    <Dialog open={open} onClose={onClose} maxWidth="md" fullWidth>
      <DialogTitle
        sx={{
          fontWeight: 900,
          bgcolor: cfg.primaryColor,
          color: '#ffffff',
          display: 'flex',
          justifyContent: 'space-between',
          alignItems: 'center',
          py: 1.2,
          px: 2.5,
        }}
      >
        <Box sx={{ display: 'flex', alignItems: 'center', gap: 1.5 }}>
          <span>Student Registration Slip</span>
          <Chip
            label={slip.slipNumber}
            size="small"
            sx={{ bgcolor: '#ffffff', color: cfg.primaryColor, fontWeight: 800 }}
          />
        </Box>
        <Chip
          label={slip.paymentStatus}
          size="small"
          color={slip.paymentStatus === 'Paid' ? 'success' : slip.paymentStatus === 'Partial' ? 'warning' : 'error'}
          sx={{ fontWeight: 800 }}
        />
      </DialogTitle>

      <DialogContent dividers sx={{ p: { xs: 1.5, sm: 2.5 }, bgcolor: '#f8fafc' }}>
        {/* Printable 1/3 A4 Compact Slip Container */}
        <Box
          id="printable-registration-slip"
          className="printable-slip"
          sx={{
            width: '100%',
            maxWidth: `${cfg.pageMaxWidth || 780}px`,
            mx: 'auto',
            bgcolor: '#ffffff',
            border:
              cfg.borderStyle === 'Double'
                ? `3px double ${cfg.borderColor}`
                : cfg.borderStyle === 'Dashed'
                ? `2px dashed ${cfg.borderColor}`
                : `2px solid ${cfg.borderColor}`,
            borderRadius: 2,
            p: `${cfg.pagePadding || 16}px`,
            boxSizing: 'border-box',
            fontFamily: cfg.fontFamily,
            color: '#0f172a',
            '@media print': {
              width: '100% !important',
              maxWidth: '100% !important',
              border: `1.5px solid ${cfg.borderColor} !important`,
              borderRadius: '0 !important',
              p: '5mm 8mm !important',
              m: '0 auto !important',
              boxShadow: 'none !important',
              pageBreakInside: 'avoid !important',
              breakInside: 'avoid !important',
            },
          }}
        >
          {sortedSections.filter((s) => s.visible !== false).map((s) => renderSection(s.key))}
        </Box>
      </DialogContent>

      <DialogActions sx={{ px: 2.5, py: 1.2, gap: 1 }}>
        <Button onClick={onClose} variant="outlined" color="inherit" size="small">
          Close
        </Button>
        {onAdmit && (
          <Button
            onClick={() => {
              onClose();
              onAdmit(slip);
            }}
            variant="contained"
            color="success"
            size="small"
            startIcon={<ConvertIcon />}
            sx={{ fontWeight: 800, textTransform: 'none' }}
          >
            Admit Student
          </Button>
        )}
        <Button
          onClick={handleShareWhatsApp}
          variant="contained"
          sx={{ bgcolor: '#25D366', color: '#ffffff', '&:hover': { bgcolor: '#128C7E' }, fontWeight: 700, textTransform: 'none' }}
          size="small"
          startIcon={<WhatsAppIcon />}
        >
          Share on WhatsApp
        </Button>
        <Button
          onClick={handlePrint}
          variant="contained"
          size="small"
          startIcon={<PrintIcon />}
          sx={{ bgcolor: cfg.primaryColor, '&:hover': { bgcolor: cfg.accentColor || cfg.primaryColor }, fontWeight: 800, textTransform: 'none' }}
        >
          Print Slip (1/3 A4)
        </Button>
      </DialogActions>
    </Dialog>
  );
};

export const AdmissionSlipModal = RegistrationSlipModal;
export default RegistrationSlipModal;
